"""Builds gate1_web/metrics_data.js from the Gate2_metrics_ship package.

Reads the metrics JSONs, per-class CSV, confusion CSVs and tsne_embeddings.csv,
then emits window.METRICS_DATA for the METRICS tab of vcm_monitor.html.
Run:  python _build_metrics_data.py
"""
import csv
import json
from pathlib import Path

SHIP = Path(r"C:/Users/Leandro/Desktop/Leandro/AI 222 and AI 231/Exercise 2/Exercise 2b/Shipping/Gate2_metrics_ship")
OUT = Path(__file__).parent / "metrics_data.js"

tsne = []
with open(SHIP / "tsne_embeddings.csv", newline="", encoding="utf-8") as f:
    for row in csv.DictReader(f):
        tsne.append({
            "ds": row["dataset"],
            "cls": row["class"],
            "file": row.get("file") or "",
            "correct": (row.get("correct") or "").strip(),
            "x": float(row["tsne_x"]),
            "y": float(row["tsne_y"]),
        })

rv = json.load(open(SHIP / "metrics_real_voice.json", encoding="utf-8"))
syn = json.load(open(SHIP / "metrics_synthetic.json", encoding="utf-8"))

def rows_of(name):
    with open(SHIP / name, newline="", encoding="utf-8") as f:
        return [row for row in csv.reader(f)]

data = {
    "tsne": tsne,
    "realVoice": rv,
    "synthetic": syn,
    "perClassRV": rows_of("per_class_real_voice.csv"),
    "confusionRV": rows_of("confusion_real_voice_150.csv"),
    "confusionSyn": rows_of("confusion_synthetic_val.csv"),
}

nl = chr(10)
parts = [
    "// Generated by _build_metrics_data.py - do not edit.",
    "// Source: Gate2_metrics_ship (performance + t-SNE embeddings for the 19-intent Gate 2 CRNN).",
    "window.METRICS_DATA = " + json.dumps(data, separators=(",", ":")) + ";",
]
with open(OUT, "w", encoding="utf-8") as f:
    f.write(nl.join(parts) + nl)
print("wrote", OUT, "bytes:", OUT.stat().st_size, "| tsne points:", len(tsne))
